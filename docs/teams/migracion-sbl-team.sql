-- Inventario y generación de cambios de FK. SOLO IMPRIME; revisar y ejecutar en el corte.
-- Conserva nombres, columnas, ON DELETE y características diferibles de las FK existentes.
DECLARE
  columnas VARCHAR2(4000);
  propietario VARCHAR2(300);
  tabla VARCHAR2(300);
  nombre VARCHAR2(300);
BEGIN
  FOR c IN (
    SELECT f.* FROM DBA_CONSTRAINTS f JOIN DBA_CONSTRAINTS p
      ON p.OWNER = f.R_OWNER AND p.CONSTRAINT_NAME = f.R_CONSTRAINT_NAME
    WHERE f.CONSTRAINT_TYPE = 'R' AND p.OWNER = 'SLB_PERSONAL' AND p.TABLE_NAME = 'EQUIPO'
  ) LOOP
    SELECT LISTAGG('"' || COLUMN_NAME || '"', ',') WITHIN GROUP (ORDER BY POSITION)
      INTO columnas FROM DBA_CONS_COLUMNS WHERE OWNER = c.OWNER AND CONSTRAINT_NAME = c.CONSTRAINT_NAME;
    propietario := DBMS_ASSERT.ENQUOTE_NAME(c.OWNER, FALSE);
    tabla := DBMS_ASSERT.ENQUOTE_NAME(c.TABLE_NAME, FALSE);
    nombre := DBMS_ASSERT.ENQUOTE_NAME(c.CONSTRAINT_NAME, FALSE);
    DBMS_OUTPUT.PUT_LINE('GRANT REFERENCES ON SBL_TEAM.EQUIPO TO ' || propietario || ';');
    DBMS_OUTPUT.PUT_LINE('ALTER TABLE ' || propietario || '.' || tabla || ' DROP CONSTRAINT ' || nombre || ';');
    DBMS_OUTPUT.PUT_LINE('ALTER TABLE ' || propietario || '.' || tabla || ' ADD CONSTRAINT ' || nombre
      || ' FOREIGN KEY (' || columnas || ') REFERENCES SBL_TEAM.EQUIPO(ID_EQUIPO)'
      || CASE WHEN c.DELETE_RULE = 'CASCADE' THEN ' ON DELETE CASCADE' WHEN c.DELETE_RULE = 'SET NULL' THEN ' ON DELETE SET NULL' ELSE '' END
      || CASE WHEN c.DEFERRABLE = 'DEFERRABLE' THEN ' DEFERRABLE INITIALLY ' || c.DEFERRED ELSE ' NOT DEFERRABLE' END
      || CASE WHEN c.STATUS = 'DISABLED' THEN ' DISABLE' ELSE ' ENABLE' END
      || CASE WHEN c.VALIDATED = 'VALIDATED' THEN ' VALIDATE;' ELSE ' NOVALIDATE;' END);
  END LOOP;
END;
