  diferencias NUMBER;
BEGIN
  SELECT COUNT(*) INTO diferencias FROM (
    SELECT ID_EQUIPO, NOMBRE, DESCRIPCION, ACTIVO FROM SLB_PERSONAL.EQUIPO
    MINUS
    SELECT ID_EQUIPO, NOMBRE, DESCRIPCION, ACTIVO FROM SBL_TEAM.EQUIPO
  );
